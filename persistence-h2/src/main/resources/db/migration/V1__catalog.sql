-- Catalog schema. H2 is the source of truth; the Lucene index is derived from it.

-- Folders added to the catalog. A folder is a scan scope, not an owner of files:
-- a file belongs to every added folder its path is inside of.
CREATE TABLE library_root (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path                  VARCHAR(4096) NOT NULL UNIQUE,  -- absolute real path
    scan_state            VARCHAR(16)   NOT NULL,         -- IDLE | SCANNING (requested or running)
    scan_outcome          VARCHAR(16),                    -- COMPLETED | UNAVAILABLE | FAILED; NULL before the first scan finishes
    scan_error            VARCHAR(4000),                  -- why the last scan didn't complete
    last_scan_started_at  TIMESTAMP WITH TIME ZONE,
    last_scan_finished_at TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Unique content; one photo can be stored in several files
CREATE TABLE photo (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_hash CHAR(64) NOT NULL UNIQUE,  -- identity hash, hex
    width        INT,
    height       INT,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Files on disk. The files of a folder are a range of paths, so a file inside
-- nested folders is stored once
CREATE TABLE photo_file (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path       VARCHAR(4096) NOT NULL UNIQUE,  -- absolute
    photo_id   BIGINT        NOT NULL REFERENCES photo (id),
    size_bytes BIGINT        NOT NULL,
    mtime_ms   BIGINT        NOT NULL,
    missing    BOOLEAN       NOT NULL DEFAULT FALSE  -- not found by the last scan; the photo is kept
);
CREATE INDEX photo_file_photo_idx ON photo_file (photo_id);

-- Processing queue: one task per photo and enricher
CREATE TABLE enrichment (
    photo_id    BIGINT       NOT NULL REFERENCES photo (id),
    enricher_id VARCHAR(128) NOT NULL,  -- "embedding:<model-id>"
    version     INT          NOT NULL,  -- version of the enricher's processing
    status      VARCHAR(16)  NOT NULL,  -- PENDING | RUNNING | DONE | FAILED
    attempts    INT          NOT NULL DEFAULT 0,
    error       VARCHAR(4000),
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (photo_id, enricher_id)
);
CREATE INDEX enrichment_queue_idx ON enrichment (enricher_id, status);

-- Orders embedding writes, so the vector index can catch up from its last commit
CREATE SEQUENCE embedding_seq;

CREATE TABLE embedding (
    photo_id   BIGINT          NOT NULL REFERENCES photo (id),
    model_id   VARCHAR(64)     NOT NULL,
    vector     VARBINARY(8192) NOT NULL,  -- float32 little-endian, L2-normalized
    seq        BIGINT          NOT NULL,  -- NEXT VALUE FOR embedding_seq on every write
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (photo_id, model_id)
);
CREATE INDEX embedding_seq_idx ON embedding (model_id, seq);
